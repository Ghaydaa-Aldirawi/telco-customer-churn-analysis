import pandas as pd
import numpy as np
df = pd.read_csv('WA_Fn-UseC_-Telco-Customer-Churn.csv')
df.head(5)
df.tail(5)

df.dtypes

df.info()

for col in df.columns:
    count = df[col].isin(['?', 'null', 'NaN', ' ']).sum()
    print(f"Column '{col}': {count} occurrences")

"""TotalCharges : the type of it is object but it must be float ( it might has " " to appear as an opject )"""

df['TotalCharges'] = pd.to_numeric(df['TotalCharges'], errors='coerce')
df['TotalCharges'].fillna(0, inplace=True)

df.info()

for col in df.columns:
    count = df[col].isin(['?', 'null', 'NaN', ' ']).sum()
    print(f"Column '{col}': {count} occurrences")

df.describe()

"""The next code performs Min-Max Normalization (Scaling by Maximum) to rescale the values of tenure, MonthlyCharges, and TotalCharges into a range between 0 and 1."""

# Normalize the data
cols_to_scale = ['tenure', 'MonthlyCharges', 'TotalCharges']
for col in cols_to_scale:
    df[col] = df[col] / df[col].max()
print(df[cols_to_scale].describe().loc[['min', 'max']])

df.columns = df.columns.str.lower().str.replace(' ', '_')
print(df.columns)

df.to_csv('telecom_churn_clean.csv', index=False)

"""Plotting the attrition rate by contract type

"""

import matplotlib.pyplot as plt
import seaborn as sns

plt.figure(figsize=(8, 5))
contract_churn = df.groupby('contract')['churn'].value_counts(normalize=True).unstack() * 100
contract_churn['Yes'].plot(kind='bar', color='skyblue') # تعديل حرف Y إلى كابيتال

plt.title('Churn Percentage by Contract Type')
plt.xlabel('Contract Type')
plt.ylabel('Churn Percentage (%)')
plt.xticks(rotation=0)
plt.show()

"""Monthly Charges Distribution by Churn Status

"""

plt.figure(figsize=(8, 5))
sns.boxplot(x='churn', y='monthlycharges', data=df, palette='Set2')

plt.title('Monthly Charges Distribution by Churn Status')
plt.xlabel('Churn Status')
plt.ylabel('Monthly Charges')
plt.show()

"""A heatmap illustrating the relationships and numerical values ​​between quantitative variables.

"""

plt.figure(figsize=(8, 6))
sns.heatmap(df[['tenure', 'monthlycharges', 'totalcharges']].corr(), annot=True, cmap='coolwarm', fmt='.2f')
plt.title('Correlation Matrix of Numerical Features')
plt.show()